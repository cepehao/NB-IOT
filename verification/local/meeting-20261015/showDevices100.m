% Read the existing per-device CSV; no simulation and no MAT loading.
meetingDeviceFolder=fileparts(mfilename('fullpath'));
meetingDeviceRoot=fileparts(fileparts(fileparts(meetingDeviceFolder)));
meetingDeviceCase=fullfile(meetingDeviceRoot,'reports','100-ue');
meetingDeviceFile=fullfile(meetingDeviceCase,'static-v1_n100_r1088_ue.csv');
meetingDevices=readtable(meetingDeviceFile);
assert(height(meetingDevices)==100 && sum(meetingDevices.created)==100 ...
    && sum(meetingDevices.delivered)==6 && sum(meetingDevices.dropped)==86 ...
    && sum(meetingDevices.unfinished)==8,'Unexpected saved case contents.');
meetingDeviceOutcome=repmat("Не завершено за 5 секунд",height(meetingDevices),1);
meetingDeviceOutcome(meetingDevices.delivered>0)="Доставлено";
meetingDeviceOutcome(meetingDevices.dropped>0)="Неудача";
meetingDeviceIndoor=repmat("Нет",height(meetingDevices),1);
meetingDeviceIndoor(logical(meetingDevices.indoor))="Да";
meetingDeviceRank=3*ones(height(meetingDevices),1);
meetingDeviceRank(meetingDevices.unfinished>0)=2;
meetingDeviceRank(meetingDevices.delivered>0)=1;
[~,meetingDeviceIndex]=sortrows([meetingDeviceRank,meetingDevices.ueId],[1 2]);
meetingDeviceRows=[num2cell(meetingDevices.ueId), ...
    num2cell(round(meetingDevices.distanceM,1)),cellstr(meetingDeviceIndoor), ...
    num2cell(meetingDevices.raAttempts),num2cell(meetingDevices.raSuccesses), ...
    cellstr(meetingDeviceOutcome)];
meetingDeviceFigure=uifigure('Name','100 устройств — условия и результат каждого', ...
    'Position',[80 80 1180 730]);
meetingDeviceGrid=uigridlayout(meetingDeviceFigure,[3 1]);
meetingDeviceGrid.RowHeight={45,'1x',55};
uilabel(meetingDeviceGrid,'Text', ...
    'Сохранённый расчёт: 100 устройств, по одному сообщению 200 байт, 5 секунд модели. Доставлено 6; неудача 86; незавершено 8.', ...
    'FontSize',14,'WordWrap','on');
uitable(meetingDeviceGrid,'Data',meetingDeviceRows(meetingDeviceIndex,:), ...
    'ColumnName',{'Номер устройства','Расстояние до станции, м','В здании?', ...
    'Попыток подключения','Успешных подключений','Итог сообщения'}, ...
    'ColumnWidth',{125,185,100,170,185,230},'RowName',{}, ...
    'ColumnEditable',false(1,6),'FontSize',13);
uilabel(meetingDeviceGrid,'Text', ...
    'Сначала показаны доставившие сообщение. Успешное подключение ещё не означает доставку. Расстояние — пространственное, с учётом разницы высот; по этой таблице нельзя выделить единственную причину неудачи.', ...
    'WordWrap','on','FontSize',13);
