classdef TestLocalCompletionPipeline < matlab.unittest.TestCase
    methods (Test)
        function buildsAndTransfersTheBoundedDevelopmentPipeline(t)
            projectRoot=fileparts(fileparts(mfilename('fullpath')));
            evidenceRoot=fullfile(projectRoot,'verification','local', ...
                'implementation-20261015','T3');
            addpath(evidenceRoot);
            pathCleanup=onCleanup(@() rmpath(evidenceRoot)); %#ok<NASGU>

            outputFolder=getenv('NBIOT_T3_OUTPUT_FOLDER');
            t.assertNotEmpty(outputFolder, ...
                'Set NBIOT_T3_OUTPUT_FOLDER to a new, empty T3 evidence folder.');
            boundedEvidenceFolder=getenv('NBIOT_T3_BOUNDED_EVIDENCE_FOLDER');
            t.assertNotEmpty(boundedEvidenceFolder, ...
                'Set NBIOT_T3_BOUNDED_EVIDENCE_FOLDER to the bounded runner output folder.');
            mode=getenv('NBIOT_T3_MODE');
            t.assertTrue(any(strcmp(mode,{'full','package-only'})), ...
                'Set NBIOT_T3_MODE to full or package-only.');
            options=struct('outputFolder',outputFolder, ...
                'realizationIds',[1037 1038 1039], ...
                'boundedEvidenceFolder',boundedEvidenceFolder,'mode',mode);
            report=runLocalCompletionPipeline(options);

            t.verifyEqual(report.caseCount,3);
            t.verifyEqual(report.realizationIds,[1037 1038 1039]);
            t.verifyEqual(report.maxUE,2);
            t.verifyTrue(report.caseVerificationPassed);
            t.verifyTrue(report.diagnosticsComplete);
            t.verifyEqual(report.fixtureKind,'development-fixture');
            t.verifyEqual(report.trainingIds,1037);
            t.verifyEqual(report.validationIds,1038);
            t.verifyEqual(report.testIds,1039);
            t.verifyEqual(report.runtimeStatus,'completed');
            t.verifyEqual(report.runtimeModelDataKind,'development-fixture');
            t.verifyTrue(report.externalFixtureAdmissionRejected);
            t.verifyEqual(report.registrySha256Before,report.registrySha256After);
            t.verifyFalse(report.engineeringCoreReady);
            t.verifyFalse(report.localReady);
            t.verifyFalse(report.externalExperimentComplete);
            if strcmp(mode,'full')
                t.verifyEqual(report.status,'core-complete');
                t.verifyFalse(report.transferReaderPassed);
                t.verifyEmpty(report.packageFile);
                t.verifyEmpty(report.localCompletionFile);
            else
                t.verifyEqual(report.status,'complete');
                t.verifyTrue(report.transferReaderPassed);
                t.verifyTrue(isfile(report.packageFile));
                t.verifyTrue(isfile(report.localCompletionFile));
                identity=report.packageOnlySourceIdentity;
                t.assertTrue(isscalar(identity), ...
                    'Package-only source identity must be one attestation structure.');
                t.verifyTrue(identity.verified);
                t.verifyEqual(identity.mode,'restricted-package-only-deltas');
                t.verifyTrue(identity.priorPackageVerificationPassed);
                t.verifyTrue(identity.coreFunctionsUnchanged);
                t.verifyTrue(identity.coreOutputSnapshotUnchanged);
                t.verifyEqual(identity.baselineImplementationDigest, ...
                    '48823e76fd5327d9a9c35a82c043806875fb734e596df6df0b5752a720072965');
                t.verifyEqual(identity.baselineImplementationDigest, ...
                    identity.coreImplementationDigest);
                t.verifyEqual(identity.coreBoundedEvidenceSuiteSha256, ...
                    'a6f0154203f308074d447a457766ffcd553dff40b2f71cacc7290ec936c0f186');
                t.verifyEqual(identity.baselineCoreBoundedEvidenceSuitePath, ...
                    'T3c19/transfer copy-f09998d09dcb/local-development-evidence/bounded-core-suite-report.json');
                bundledSuite=fullfile(report.packageFolder,'local-development-evidence', ...
                    'bounded-core-suite-report.json');
                t.assertTrue(isfile(bundledSuite), ...
                    'The bounded core suite report must be present in the transferred package.');
                t.verifyEqual(nbiot.ml.fileSha256(bundledSuite), ...
                    identity.coreBoundedEvidenceSuiteSha256);
                handoff=jsondecode(fileread(fullfile(report.packageFolder,'handoff-manifest.json')));
                suiteEntry=find(strcmp({handoff.files.name}, ...
                    'local-development-evidence/bounded-core-suite-report.json'),1);
                t.assertNotEmpty(suiteEntry, ...
                    'The handoff manifest must list the bounded core suite report.');
                t.verifyEqual(handoff.files(suiteEntry).sha256, ...
                    identity.coreBoundedEvidenceSuiteSha256);
                t.verifyEqual(identity.baselineSourceDigest, ...
                    'f09998d09dcb092e19c7ae5dc6a64dd26f8eaf17b7cfc68d2c7e84784bc126cd');
                t.verifyEqual(identity.baselinePackageSha256, ...
                    'a3d8751749d32e9e37091fef4912efb5849bc3256f72711b2e32ff55b1cf36ba');
                t.verifyEqual(identity.baselineHandoffManifestSha256, ...
                    '5838b268fc4a1cbbba7a65f8b0062ecbdb15b33489fb0a0f48fa8147729afa9e');
                t.verifyEqual(identity.baselinePackageVerificationSha256, ...
                    '86545c104104627dcda4bf0b743ee617e882bc1ddc50a4e80d14255fb56a33c3');
                t.verifyEqual(identity.baselineSuiteReportSha256, ...
                    '2b81d92576763711aa017ed78fd8722c015d92b4659501043455a6d53bce5922');
                t.verifyEqual(identity.baselinePreflightSha256, ...
                    '87375824087ca6a35b97f07dc55f10594d20117b9f8dec8d948e408682e5f8a1');
                t.verifyEqual(identity.coreHashHelperSha256, ...
                    '7e68441e819e97248068626ddb5b47abb73d6c1d9e876686f4d2d17472111941');
                completion=jsondecode(fileread(report.localCompletionFile));
                t3At=find(strcmp({completion.taskStates.task},'T3'),1);
                f12At=find(strcmp({completion.requirementDecisions.id},'F12'),1);
                t.assertNotEmpty(t3At, ...
                    'The completion manifest must contain the T3 task state.');
                t.assertNotEmpty(f12At, ...
                    'The completion manifest must contain the F12 decision.');
                t.verifyTrue(contains(string(completion.taskStates(t3At).status), ...
                    'independent-review-pending'), ...
                    'T3 review cannot pass before the digest-specific report exists.');
                t.verifyEqual(completion.requirementDecisions(f12At).status, ...
                    'package-pending-independent-review');
                t.verifyTrue(contains( ...
                    string(completion.requirementDecisions(f12At).reviewerEvidence), ...
                    'review pending'));
                completionReports=string(completion.reports(:));
                boundedEvidencePath=strrep(char(string(boundedEvidenceFolder)),'\','/');
                rootPath=strrep(projectRoot,'\','/');
                if startsWith(boundedEvidencePath,[rootPath '/'],'IgnoreCase',true)
                    boundedEvidencePath=boundedEvidencePath(numel(rootPath)+2:end);
                end
                boundedEvidencePath=regexprep(boundedEvidencePath,'^/+','');
                currentSuiteReport=[boundedEvidencePath '/suite-report.json'];
                deferredReviewReport=sprintf( ...
                    'verification/local/runtime-review/T3/package-identity-review-%s.md', ...
                    char(string(completion.sourceDigest(1:12))));
                t.verifyTrue(any(completionReports==string(deferredReviewReport)), ...
                    'The deferred review path must identify the current source digest.');
                for reportIndex=1:numel(completionReports)
                    reportPath=completionReports(reportIndex);
                    if strcmp(char(reportPath),currentSuiteReport)|| ...
                            strcmp(char(reportPath),deferredReviewReport)
                        continue
                    end
                    reportFile=fullfile(projectRoot, ...
                        strrep(char(reportPath),'/',filesep));
                    t.assertTrue(isfile(reportFile),sprintf( ...
                        'Completion report path is missing: %s',char(reportPath)));
                end
                expectedChanges={ ...
                    'README.md', ...
                    'docs/current-state.md', ...
                    'docs/local-completion-handoff.md', ...
                    'docs/section-50-readiness.md', ...
                    'docs/superpowers/plans/2026-10-15-local-completion-and-external-experiments/remaining-work-20261018.md', ...
                    'experiments/prepareExternalRun.m', ...
                    'tests/TestLocalCompletionPipeline.m', ...
                    'verification/local/implementation-20261015/T3/runLocalCompletionPipeline.m'};
                t.verifyEqual(sort(string(identity.changedPaths(:))), ...
                    sort(string(expectedChanges(:))));
                t.verifyTrue(completion.packageOnlySourceIdentity.verified);
                t.verifyEqual(completion.packageOnlySourceIdentity.currentSourceDigest, ...
                    report.sourceDigest);
            end
        end
    end
end
